// The slim chrome: the Inbox note, the help overlay's hints switch, the breadcrumb. :7802.
const { chromium } = require('C:/Users/ryans/AppData/Local/npm-cache/_npx/9833c18b2d85bc59/node_modules/playwright');
const path = require('node:path');
const fs = require('node:fs');
const OUT = path.join(__dirname, 'shots-chrome');
fs.mkdirSync(OUT, { recursive: true });
let n = 0; const results = [];
const check = (name, ok, extra = '') => { results.push([ok ? 'PASS' : 'FAIL', name, extra]); console.log(`${ok ? 'PASS' : 'FAIL'} ${name} ${extra}`); };
const shot = async (page, name) => { n += 1; await page.screenshot({ path: path.join(OUT, `${String(n).padStart(2, '0')}-${name}.png`) }); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Users/ryans/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('http://127.0.0.1:7802/');
  await page.evaluate(() => localStorage.setItem('cc-control.welcomed.v2', '1'));
  await page.reload();
  await sleep(1200);
  await page.keyboard.press('1');
  await sleep(300);
  const header = await page.locator('header').innerText();
  check('breadcrumb says Sessions, no lane beside it', /Sessions/.test(header) && !/Ticket Line/.test(header));
  check('no Search button, no footer legend', !/Search/.test(header) && (await page.locator('footer').count()) === 0);
  const inbox = page.getByRole('region', { name: 'Inbox' }).or(page.locator('section[aria-label="Inbox"]'));
  const note = await inbox.locator('div.text-xs').first().innerText();
  check('Inbox note reads like the others', /Your tickets/.test(note) && /Ready for QA/.test(note), note);
  check('lane bar says Lane, not Workspace', /Lane/.test(await page.locator('main').innerText()) && !/\+ Workspace|Workspace W/.test(await page.locator('main').innerText()));
  await shot(page, 'board');
  await page.keyboard.press('v');
  await sleep(300);
  const note2 = await inbox.locator('div.text-xs').first().innerText();
  check('v switches the Inbox view in the note', /Ready for QA in your projects/.test(note2) && /Mine/.test(note2), note2);
  await page.keyboard.press('v');
  await sleep(200);
  // The help overlay's switch.
  await page.keyboard.press('Shift+Slash');
  await sleep(400);
  const sw = page.getByRole('switch');
  check('help has a shortcut-hints switch, on', (await sw.count()) === 1 && (await sw.getAttribute('aria-checked')) === 'true');
  await shot(page, 'help-switch-on');
  await page.keyboard.press('h');
  await sleep(400);
  check('H turns it off', (await sw.getAttribute('aria-checked')) === 'false');
  await page.keyboard.press('Escape');
  await sleep(300);
  const kcVisible = await page.locator('main .kc').evaluateAll((els) => els.filter((e) => e.offsetParent !== null).length);
  check('no keycaps visible on the board with hints off', kcVisible === 0, `(${kcVisible})`);
  await shot(page, 'board-no-hints');
  await page.keyboard.press('Shift+Slash');
  await sleep(300);
  await page.keyboard.press('h');
  await sleep(300);
  check('H turns it back on', (await sw.getAttribute('aria-checked')) === 'true');
  await page.keyboard.press('Escape');
  check('no console errors', errors.length === 0, errors.join(' | ').slice(0, 300));
  await browser.close();
  const fails = results.filter((r) => r[0] === 'FAIL');
  console.log(`\n${results.length - fails.length}/${results.length} passed`);
  process.exit(fails.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
